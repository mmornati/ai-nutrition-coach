// Drift database for the AI Nutrition Coach local encrypted store.
//
// Schema:
//   * `plate_log_table`             — one row per logged meal
//     (Story 1.2).
//   * `food_entry_table`            — denormalised `DatabaseFood` +
//     `QuantityRange` columns back-referenced to
//     `plate_log_table.id` (Story 1.2).
//   * `coach_note_table`            — one row per post-resolve coach
//     note (Story 2.2). FK back-ref to `plate_log_table.id` at the
//     use-case layer (no DB-level FK constraint — matches the
//     `food_entry_table` convention).
//   * `coach_interaction_table`     — append-only record of one
//     user action against a coach whisper (Story 2.3). FK
//     back-ref to `coach_note_table.id` at the use-case layer
//     (same convention as the rest of the schema).
//   * `coach_dismissal_table`       — durable "quiet" markers for
//     dismissed whispers / open-plate hints (v4, F6).
//   * `kv_table`                    — small encrypted key/value facts (v5).
//
// There is deliberately NO sync-queue table: v1 has no sync transport, so a
// persisted outbox would only accumulate rows nothing consumes. The queue is
// in-memory (`InMemorySyncQueue`) behind the `SyncQueue` port; a durable table
// arrives with the first real transport (security review F4).
//
// Schema history:
//   * v1 — `plate_log_table`, `food_entry_table`.
//   * v2 — `coach_note_table`.
//   * v3 — `coach_interaction_table`.
//   * v4 — `food_entry_table.food_group` (F2; default `other`),
//     `coach_dismissal_table` (F6), the three plate-lookup indexes
//     (`idx_plate_logged_at`, `idx_entry_plate`, `idx_note_plate`) and the
//     millisecond normalisation of legacy `logged_at_utc` values. Re-runnable.
//   * v5 — `kv_table` (small encrypted key/value facts: web AI settings and
//     BYOK key, last-export time). Re-runnable (`CREATE TABLE IF NOT EXISTS`).
//
// Encryption (AD-8): the underlying `NativeDatabase` is opened with a
// `setup` callback that runs the sqlite3mc key pragma. The key bytes come
// from `SecureKeySource` (Keychain/Keystore under
// `ai_nutrition_coach_db_key_v1`); this class is deliberately key-agnostic so the
// adapter wiring stays testable with an in-memory `NativeDatabase`.
//
// Codegen: the `part` directive points at `app_database.g.dart`, which is
// committed and generated by `melos run build:runner` (drift_dev). Never
// edit it by hand.

import 'package:drift/drift.dart';

import 'tables/coach_dismissal_table.dart';
import 'tables/coach_interaction_table.dart';
import 'tables/coach_note_table.dart';
import 'tables/food_entry_table.dart';
import 'tables/kv_table.dart';
import 'tables/plate_log_table.dart';

part 'app_database.g.dart';

/// The database on disk was written by a NEWER schema than this build knows
/// (a restored backup, or a browser tab still running an older cached build
/// next to a newer one). Opening it would run the old code over a newer layout,
/// so the open is refused instead; the app says so calmly and asks the user to
/// reload to update. Never carries data.
class SchemaTooNewException implements Exception {
  const SchemaTooNewException({required this.found, required this.supported});

  final int found;
  final int supported;

  @override
  String toString() =>
      'SchemaTooNewException(found: $found, supported: $supported)';
}

@DriftDatabase(
  tables: [
    PlateLogTable,
    FoodEntryTable,
    CoachNoteTable,
    CoachInteractionTable,
    CoachDismissalTable,
    KvTable,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor);

  @override
  int get schemaVersion => 5;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) => m.createAll(),
    onUpgrade: (m, from, to) async {
      // Drift runs this for downgrades too (from > to).
      if (from > to) {
        throw SchemaTooNewException(found: from, supported: to);
      }
      if (from < 2) {
        await m.createTable(coachNoteTable);
      }
      if (from < 3) {
        await m.createTable(coachInteractionTable);
      }
      if (from < 4) {
        await _upgradeToV4(m);
      }
      if (from < 5) {
        await _upgradeToV5(m);
      }
    },
  );

  /// The v3 -> v4 step, written to be RE-RUNNABLE: a database whose
  /// `user_version` was rolled back (restored backup, downgrade then
  /// upgrade) already has the column / table / indexes, and a plain
  /// `ALTER TABLE ADD COLUMN` would fail with "duplicate column" and strand
  /// the user. Each part checks before it acts, `CREATE ... IF NOT EXISTS`
  /// covers the rest, and the whole step is one transaction.
  Future<void> _upgradeToV4(Migrator m) async {
    await transaction(() async {
      // F2: existing rows get 'other' (their group was never stored).
      final columns = await customSelect(
        'PRAGMA table_info(food_entry_table)',
      ).get();
      final hasGroup = columns.any(
        (c) => c.read<String>('name') == 'food_group',
      );
      if (!hasGroup) {
        await m.addColumn(foodEntryTable, foodEntryTable.foodGroup);
      }
      // F6 (drift's `createTable` is `CREATE TABLE IF NOT EXISTS`).
      await m.createTable(coachDismissalTable);
      // Indexes for the range reads (F8 follow-up).
      // (Literal SQL, kept in step with the `@TableIndex` annotations by
      // the "fresh v4 == upgraded" schema test.)
      for (final statement in const [
        'CREATE INDEX IF NOT EXISTS idx_plate_logged_at '
            'ON plate_log_table (logged_at_utc)',
        'CREATE INDEX IF NOT EXISTS idx_entry_plate '
            'ON food_entry_table (plate_log_id)',
        'CREATE INDEX IF NOT EXISTS idx_note_plate '
            'ON coach_note_table (plate_log_id)',
      ]) {
        await customStatement(statement);
      }
      // Legacy timestamps carried microseconds (`...00.123456Z`, 27 chars);
      // the range queries compare the TEXT, which is only exact when every
      // value has the same millisecond width (`...00.123Z`, 24 chars).
      // Truncating (not rounding) keeps the instant within the same
      // millisecond.
      await customStatement(
        "UPDATE plate_log_table SET logged_at_utc = "
        "substr(logged_at_utc, 1, 23) || 'Z' "
        'WHERE length(logged_at_utc) > 24',
      );
    });
  }

  /// The v4 -> v5 step: the key/value table. Re-runnable for the same reason
  /// as [_upgradeToV4] (drift's `createTable` is `CREATE TABLE IF NOT EXISTS`).
  Future<void> _upgradeToV5(Migrator m) async {
    await m.createTable(kvTable);
  }
}
